REALISTIC_FAMILY_TRACKS = {
    "subgenre_hybrid_realistic_family",
    "sample_track_d_realistic_family",
}


def resolve_segment_task(segment_id: str, subgenre_track: str, sample_track: str) -> str:
    """根据 subgenre/sample track 路由到分段任务模板，
    现实-家族返乡走克制生活流模板，其他默认走原打脸短剧模板。"""
    sid = segment_id or "hook"
    track_keys = {str(subgenre_track or "").strip(), str(sample_track or "").strip()}
    if track_keys & REALISTIC_FAMILY_TRACKS:
        return TESTING_SEGMENT_TASKS_REALISTIC_FAMILY.get(
            sid, TESTING_SEGMENT_TASKS_REALISTIC_FAMILY["hook"]
        )
    return TESTING_SEGMENT_TASKS.get(sid, TESTING_SEGMENT_TASKS["hook"])
